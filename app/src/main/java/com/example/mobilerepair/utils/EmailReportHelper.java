package com.example.mobilerepair.utils;

import android.content.Context;
import android.content.Intent;
import android.content.SharedPreferences;
import android.net.Uri;
import android.widget.Toast;

import com.example.mobilerepair.data.model.RepairItem;

import java.text.SimpleDateFormat;
import java.util.Date;
import java.util.List;
import java.util.Locale;

public class EmailReportHelper {

    public static final String DEFAULT_RECEIVER_EMAIL = "gajanan.pande094@gmail.com";
    private static final String PREF_NAME = "MobileRepairPrefs";
    private static final String KEY_RECEIVER_EMAIL = "static_receiver_email";

    public static String getReceiverEmail(Context context) {
        SharedPreferences prefs = context.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE);
        return prefs.getString(KEY_RECEIVER_EMAIL, DEFAULT_RECEIVER_EMAIL);
    }

    public static void setReceiverEmail(Context context, String email) {
        SharedPreferences prefs = context.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE);
        prefs.edit().putString(KEY_RECEIVER_EMAIL, email.trim()).apply();
    }

    public static String buildDailyReportText(List<RepairItem> todayItems, int totalAmount) {
        String dateStr = new SimpleDateFormat("dd MMM yyyy", Locale.getDefault()).format(new Date());
        String timeStr = new SimpleDateFormat("hh:mm a", Locale.getDefault()).format(new Date());

        StringBuilder body = new StringBuilder();
        body.append("=========================================\n");
        body.append("   RAJPUT MOBILE REPAIR SHOP - DAILY REPORT   \n");
        body.append("=========================================\n");
        body.append("Date: ").append(dateStr).append(" at ").append(timeStr).append("\n");
        body.append("Total Revenue Collected: ₹").append(totalAmount).append("\n");
        body.append("Total Entries Count: ").append(todayItems.size()).append("\n");
        body.append("-----------------------------------------\n\n");
        body.append("ITEMIZED SALES BREAKDOWN:\n\n");

        if (todayItems.isEmpty()) {
            body.append("No sales entries recorded for today yet.\n");
        } else {
            int count = 1;
            for (RepairItem item : todayItems) {
                String model = (item.getMobileCompanyName() != null ? item.getMobileCompanyName() : "") +
                        (item.getMobileModelNumber() != null ? " " + item.getMobileModelNumber() : "");

                body.append(count++).append(". ").append(item.getCustomerName() != null ? item.getCustomerName() : "N/A").append("\n");
                body.append("   Mobile: ").append(item.getMobileNumber() != null ? item.getMobileNumber() : "N/A").append("\n");
                body.append("   Device: ").append(model.trim().isEmpty() ? "N/A" : model.trim()).append("\n");
                body.append("   Issue: ").append(item.getIssueDescription() != null ? item.getIssueDescription() : "N/A").append("\n");
                body.append("   Address: ").append(item.getAddress() != null ? item.getAddress() : "N/A").append("\n");
                body.append("   Amount: ₹").append(item.getTotalAmount()).append("\n");
                body.append("   Date/Time: ").append(item.getCreatedDate() != null ? item.getCreatedDate() : "N/A").append("\n");
                body.append("   --------------------------------------\n");
            }
        }

        body.append("\nReport automatically generated by Mobile Repair Hub System.");
        return body.toString();
    }

    public static void sendAutoDailyEmailReport(Context context, List<RepairItem> todayItems, int totalAmount) {
        String receiverEmail = getReceiverEmail(context);
        String dateStr = new SimpleDateFormat("dd MMM yyyy", Locale.getDefault()).format(new Date());

        String subject = "Daily Sales Collection Report - " + dateStr + " [₹" + totalAmount + "]";
        String bodyText = buildDailyReportText(todayItems, totalAmount);

        Intent intent = new Intent(Intent.ACTION_SENDTO);
        intent.setData(Uri.parse("mailto:" + Uri.encode(receiverEmail)));
        intent.putExtra(Intent.EXTRA_EMAIL, new String[]{receiverEmail});
        intent.putExtra(Intent.EXTRA_SUBJECT, subject);
        intent.putExtra(Intent.EXTRA_TEXT, bodyText);

        try {
            Intent chooser = Intent.createChooser(intent, "Sending Daily Collection Mail to " + receiverEmail);
            chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            context.startActivity(chooser);
        } catch (Exception e) {
            Toast.makeText(context, "No email client found to send report", Toast.LENGTH_SHORT).show();
        }
    }
}
